/**
 * Writes `vectors/wire-vectors.json`, the file both implementations are tested against.
 *
 * The point of committing sealed payloads rather than generating them on both sides is that
 * GCM nonces are random: two implementations sealing the same plaintext produce different
 * bytes, so agreement can only be proved by one side *opening* what the other sealed. These
 * vectors are produced here, checked in, verified by `envelope.test.ts`, and verified again by
 * `WireVectorsTest.kt` in the Android project — which is the actual gate. If the header layout,
 * the AAD binding, the UUID byte order or the counter's endianness ever drift apart, that test
 * fails rather than a family member's messages arriving as garbage.
 *
 * Regenerate with `npm run vectors` only when the format itself changes, and expect to run the
 * Android test afterwards.
 */
import { writeFileSync } from 'node:fs';
import { buildHeader, seal } from '../src/lib/crypto/envelope';
import { importKey } from '../src/lib/crypto/aead';
import { encodeInvite } from '../src/lib/crypto/invite';
import { encodeChat } from '../src/lib/mqtt/chatMessages';
import { encodeControl } from '../src/lib/mqtt/controlMessages';
import { encodeCall } from '../src/lib/mqtt/callMessages';
import { encodeAudio } from '../src/lib/mqtt/audioMessages';
import { encodeLocation } from '../src/lib/mqtt/locationMessages';
import { fromHex, toBase64, toHex, utf8 } from '../src/lib/util/bytes';

// Fixed inputs, so a regeneration changes only the ciphertexts and not what they mean.
const KEY_HEX = '000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f';
const SENDER = '3f2504e0-4f89-11d3-9a0c-0305e82c3301';
const GROUP_KEY_HEX = '202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f';

const vectors = async () => {
	const key = await importKey(fromHex(KEY_HEX));

	const envelopes = [];
	for (const [epoch, counter, text] of [
		[0, 1n, 'hello'],
		[0, 4294967296n, 'a counter past 32 bits'],
		[255, 18446744073709551615n, 'the largest epoch and counter this format holds']
	] as const) {
		envelopes.push({
			epoch,
			senderId: SENDER,
			counter: counter.toString(),
			plaintextUtf8: text,
			header: toHex(buildHeader(epoch, SENDER, counter)),
			sealed: toBase64(await seal(key, epoch, SENDER, counter, utf8(text)))
		});
	}

	return {
		note: 'Generated by scripts/generate-vectors.ts. Both implementations must open these.',
		keyHex: KEY_HEX,
		envelopes,
		invite: encodeInvite({
			groupId: '9b1deb4d-3b7d-4bad-9bdd-2b0d7b3dcb6d',
			groupName: 'Keluarga',
			adminId: SENDER,
			epoch: 0,
			groupKey: fromHex(GROUP_KEY_HEX),
			host: 'broker.example',
			port: 8883,
			tls: true,
			allowInsecureTls: false,
			username: 'ayah',
			password: 'rahasia',
			topicPrefix: 'familygroup'
		}),
		chat: {
			text: toBase64(
				encodeChat({ kind: 'text', id: 'm-1', body: 'Sudah sampai?', replyToId: null })
			),
			attachment: toBase64(
				encodeChat({
					kind: 'attachment',
					id: 'm-2',
					attachmentKind: 'image',
					blobId: 'b-1',
					mime: 'image/jpeg',
					sizeBytes: 51234,
					sha256: 'a'.repeat(64),
					caption: 'di depan rumah',
					replyToId: 'm-1'
				})
			)
		},
		control: {
			profile: toBase64(
				encodeControl({
					kind: 'profile',
					userId: SENDER,
					displayName: 'Ayah',
					avatar: fromHex('cafebabe')
				})
			),
			kick: toBase64(encodeControl({ kind: 'kick', targetUserId: SENDER })),
			locset: toBase64(
				encodeControl({
					kind: 'locset',
					enabled: true,
					sampleSec: 60,
					pushSec: 300,
					minDistanceM: 25,
					retentionHours: 168
				})
			)
		},
		call: {
			offer: toBase64(
				encodeCall({
					kind: 'offer',
					callId: 'c-1',
					toUserId: '9b1deb4d-3b7d-4bad-9bdd-2b0d7b3dcb6d',
					mode: 'audio',
					ttlSec: 45
				})
			),
			// A group offer: no target, so every member rings. The vector exists because the
			// difference between "absent" and "empty string" is exactly the kind of thing two
			// implementations drift on, and an empty target reads as a call to nobody.
			groupOffer: toBase64(
				encodeCall({ kind: 'offer', callId: 'c-2', toUserId: null, mode: 'audio', ttlSec: 45 })
			),
			// A buzz: same shape, different mode. The vector exists because an older build must
			// drop this rather than ring for it as though it were a voice call.
			buzzOffer: toBase64(
				encodeCall({ kind: 'offer', callId: 'c-3', toUserId: null, mode: 'buzz', ttlSec: 90 })
			),
			ring: toBase64(encodeCall({ kind: 'ring', callId: 'c-1' })),
			accept: toBase64(encodeCall({ kind: 'accept', callId: 'c-1' })),
			declineBusy: toBase64(encodeCall({ kind: 'decline', callId: 'c-1', reason: 'busy' })),
			cancel: toBase64(encodeCall({ kind: 'cancel', callId: 'c-1' })),
			end: toBase64(encodeCall({ kind: 'end', callId: 'c-1' }))
		},
		// Binary, unlike every other codec here, so the vector proves byte order as well as
		// field order — big-endian on both sides, which is ByteBuffer's default and DataView's
		// explicit `false`.
		audio: toBase64(
			encodeAudio({
				streamId: 0x01020304,
				seq: 0xfffffffe,
				frames: [fromHex('cafebabe'), fromHex('00'), fromHex('deadbeefdeadbeef')]
			})
		),
		location: toBase64(
			encodeLocation({
				lat: -6.914744,
				lon: 107.60981,
				accuracy: 12.5,
				speed: 1.25,
				bearing: 180,
				capturedAt: 1757404800000
			})
		)
	};
};

vectors().then((v) => {
	writeFileSync('vectors/wire-vectors.json', JSON.stringify(v, null, 2) + '\n');
	console.log('wrote vectors/wire-vectors.json');
});
